-- BilaForm browser-first Supabase schema. Review and run in Supabase SQL Editor.
-- Uses auth.uid() + RLS for every account-owned record.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_name_length check (char_length(full_name) between 0 and 100)
);

create or replace function public.create_bilaform_profile()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists bilaform_auth_user_profile on auth.users;
create trigger bilaform_auth_user_profile after insert on auth.users
for each row execute function public.create_bilaform_profile();

create table if not exists public.budgets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  cash bigint not null check (cash between 0 and 1000000000),
  essentials bigint not null check (essentials between 0 and 1000000000),
  buffer bigint not null check (buffer between 0 and 1000000000),
  days integer not null check (days between 1 and 366),
  daily_safe bigint not null check (daily_safe >= 0),
  updated_at timestamptz not null default now()
);
create index if not exists budgets_user_latest on public.budgets(user_id, updated_at desc, id desc);

create table if not exists public.plans (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null default 'vukamonth',
  name text not null check (char_length(name) between 1 and 60),
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists plans_user_latest on public.plans(user_id, created_at desc, id desc);

create table if not exists public.savings_goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  target_amount bigint not null check (target_amount between 1 and 1000000000),
  current_amount bigint not null default 0 check (current_amount between 0 and target_amount),
  target_date date not null,
  status text not null default 'active' check (status in ('active','paused','completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists savings_goals_user_target on public.savings_goals(user_id, target_date, id desc);

create table if not exists public.savings_contributions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  goal_id bigint not null references public.savings_goals(id) on delete cascade,
  amount bigint not null check (amount > 0),
  entry_type text not null check (entry_type in ('initial','contribution')),
  created_at timestamptz not null default now()
);
create index if not exists savings_contributions_user_goal on public.savings_contributions(user_id, goal_id, created_at desc, id desc);

create or replace function public.record_initial_goal_contribution()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.current_amount > 0 then
    insert into public.savings_contributions(user_id, goal_id, amount, entry_type)
    values (new.user_id, new.id, new.current_amount, 'initial');
  end if;
  return new;
end;
$$;
drop trigger if exists bilaform_goal_initial_contribution on public.savings_goals;
create trigger bilaform_goal_initial_contribution after insert on public.savings_goals
for each row execute function public.record_initial_goal_contribution();

create or replace function public.add_savings_contribution(p_goal_id bigint, p_amount bigint)
returns public.savings_goals language plpgsql security definer set search_path = '' as $$
declare goal public.savings_goals;
begin
  if auth.uid() is null or p_amount is null or p_amount < 1 then raise exception 'Enter a valid contribution amount.'; end if;
  select * into goal from public.savings_goals where id = p_goal_id and user_id = auth.uid() for update;
  if not found then raise exception 'Savings goal not found.'; end if;
  if goal.status <> 'active' then raise exception 'Resume this savings goal before adding a contribution.'; end if;
  if goal.current_amount + p_amount > goal.target_amount then raise exception 'Contribution exceeds the remaining amount.'; end if;
  update public.savings_goals set current_amount = current_amount + p_amount,
    status = case when current_amount + p_amount >= target_amount then 'completed' else status end,
    updated_at = now() where id = goal.id returning * into goal;
  insert into public.savings_contributions(user_id, goal_id, amount, entry_type)
  values (auth.uid(), goal.id, p_amount, 'contribution');
  return goal;
end;
$$;
revoke all on function public.add_savings_contribution(bigint,bigint) from public;
grant execute on function public.add_savings_contribution(bigint,bigint) to authenticated;

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 100),
  email text not null check (char_length(email) between 3 and 254),
  message text not null check (char_length(message) between 10 and 5000),
  created_at timestamptz not null default now()
);

