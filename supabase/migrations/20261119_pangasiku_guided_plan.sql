-- Additive PangaSiku detail and daily spending records. Existing budget history is preserved.
alter table public.budgets
  add column if not exists other_income bigint not null default 0 check (other_income between 0 and 1000000000),
  add column if not exists cash_location text,
  add column if not exists payday_date date,
  add column if not exists expense_items jsonb not null default '[]'::jsonb;
grant update (cash, essentials, buffer, days, daily_safe, other_income, cash_location, payday_date, expense_items, updated_at) on public.budgets to authenticated;

create unique index if not exists budgets_user_id_pair on public.budgets(user_id, id);

create table if not exists public.daily_spending (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  budget_id bigint,
  description text not null check (char_length(description) between 1 and 100),
  amount bigint not null check (amount between 1 and 1000000000),
  spent_on date not null default current_date,
  created_at timestamptz not null default now()
);
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'daily_spending_own_budget') then
    alter table public.daily_spending add constraint daily_spending_own_budget
      foreign key (user_id, budget_id) references public.budgets(user_id, id) on delete cascade;
  end if;
end $$;
create index if not exists daily_spending_user_date on public.daily_spending(user_id, spent_on desc, id desc);
alter table public.daily_spending enable row level security;
drop policy if exists "Users manage own daily spending" on public.daily_spending;
create policy "Users manage own daily spending" on public.daily_spending
  for all to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
grant select, insert, delete on public.daily_spending to authenticated;
grant usage, select on sequence public.daily_spending_id_seq to authenticated;
